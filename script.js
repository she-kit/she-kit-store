let currentLanguage = 'he';
let currentTheme = 'dark';
let currentTeam = null;
let currentKit = null;
let cart = [];

document.addEventListener('DOMContentLoaded', () => {
    initializeTheme();
    initializeLanguage();
    setupEventListeners();
    loadCart();
});

function initializeTheme() {
    const saved = localStorage.getItem('theme') || 'dark';
    currentTheme = saved;
    applyTheme(currentTheme);
}

function applyTheme(theme) {
    const html = document.documentElement;
    if (theme === 'light') {
        html.setAttribute('data-theme', 'light');
    } else {
        html.removeAttribute('data-theme');
    }
    updateThemeButton();
}

function toggleTheme() {
    currentTheme = currentTheme === 'dark' ? 'light' : 'dark';
    localStorage.setItem('theme', currentTheme);
    applyTheme(currentTheme);
}

function updateThemeButton() {
    const btn = document.getElementById('themeToggle');
    btn.textContent = currentTheme === 'dark' ? '☀️' : '🌙';
}

function initializeLanguage() {
    const saved = localStorage.getItem('language') || 'he';
    currentLanguage = saved;
    applyLanguage(currentLanguage);
}

function applyLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    const html = document.documentElement;
    html.lang = lang;
    html.dir = lang === 'he' || lang === 'ar' ? 'rtl' : 'ltr';
    
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });
    
    document.getElementById('languageSelect').value = lang;
}

function setupEventListeners() {
    document.getElementById('themeToggle').addEventListener('click', toggleTheme);
    document.getElementById('languageSelect').addEventListener('change', (e) => {
        applyLanguage(e.target.value);
    });
    
    document.querySelectorAll('.league-toggle').forEach(btn => {
        btn.addEventListener('click', function() {
            const teamsList = this.nextElementSibling;
            teamsList.classList.toggle('hidden');
        });
    });
    
    document.querySelectorAll('.team-link').forEach(link => {
        link.addEventListener('click', (e) => {
            e.preventDefault();
            const teamName = link.getAttribute('data-team');
            goToTeam(teamName);
        });
    });
    
    document.getElementById('cartBtn').addEventListener('click', goToCart);
    
    document.querySelector('.cta-button')?.addEventListener('click', () => {
        document.getElementById('homePage').classList.remove('active');
        document.getElementById('cartPage').classList.remove('active');
        document.getElementById('kitPage').classList.remove('active');
        const firstLeague = document.querySelector('.league-item');
        if (firstLeague) {
            firstLeague.querySelector('.league-toggle').click();
        }
    });
    
    setupPriceCalculations();
}

function goHome() {
    showPage('homePage');
}

function goToTeam(teamName) {
    currentTeam = teamName;
    document.getElementById('teamName').textContent = teamName;
    showPage('teamPage');
}

function goToKit(kitType) {
    currentKit = kitType;
    const kitNames = {
        home: translations[currentLanguage].homeKit || 'Home Kit',
        away: translations[currentLanguage].awayKit || 'Away Kit',
        third: translations[currentLanguage].thirdKit || 'Third Kit'
    };
    document.getElementById('kitTitle').textContent = `${currentTeam} - ${kitNames[kitType]}`;
    resetCustomizationForm();
    showPage('kitPage');
}

function showPage(pageId) {
    document.querySelectorAll('.page').forEach(page => {
        page.classList.remove('active');
    });
    document.getElementById(pageId).classList.add('active');
}

function selectKit(kitType) {
    goToKit(kitType);
}

function setupPriceCalculations() {
    document.getElementById('playerName').addEventListener('input', calculatePrice);
    document.getElementById('playerNumber').addEventListener('input', calculatePrice);
    document.querySelectorAll('.addon').forEach(checkbox => {
        checkbox.addEventListener('change', calculatePrice);
    });
    document.getElementById('shortsPack').addEventListener('change', calculatePrice);
    document.getElementById('quantity').addEventListener('change', calculatePrice);
}

function calculatePrice() {
    let price = 99;
    let addonsTotal = 0;
    
    if (document.getElementById('playerNumber').value) {
        addonsTotal += 20;
    }
    
    document.querySelectorAll('.addon:checked').forEach(() => {
        addonsTotal += 5;
    });
    
    if (document.getElementById('shortsPack').checked) {
        addonsTotal += 50;
    }
    
    const quantity = parseInt(document.getElementById('quantity').value) || 1;
    const total = (price + addonsTotal) * quantity;
    
    document.getElementById('basePrice').textContent = `${price}₪`;
    document.getElementById('addonsPrice').textContent = `${addonsTotal}₪`;
    document.getElementById('totalPrice').textContent = `${total}₪`;
}

function addToCart() {
    const name = document.getElementById('playerName').value || 'ללא שם';
    const number = document.getElementById('playerNumber').value || 'ללא מספר';
    const addons = Array.from(document.querySelectorAll('.addon:checked')).map(c => c.value);
    const hasShorts = document.getElementById('shortsPack').checked;
    const version = document.querySelector('input[name="version"]:checked').value;
    const quantity = parseInt(document.getElementById('quantity').value) || 1;
    
    let price = 99;
    if (number) price += 20;
    if (addons.length > 0) price += addons.length * 5;
    if (hasShorts) price += 50;
    
    const item = {
        id: Date.now(),
        team: currentTeam,
        kit: currentKit,
        name: name,
        number: number,
        addons: addons,
        shorts: hasShorts,
        version: version,
        quantity: quantity,
        price: price,
        total: price * quantity
    };
    
    cart.push(item);
    saveCart();
    updateCartCount();
    
    alert('✅ נוסף לעגלה!');
    goHome();
}

function removeFromCart(itemId) {
    cart = cart.filter(item => item.id !== itemId);
    saveCart();
    updateCartCount();
    displayCartItems();
}

function displayCartItems() {
    const cartItems = document.getElementById('cartItems');
    const cartFooter = document.getElementById('cartFooter');
    
    if (cart.length === 0) {
        cartItems.innerHTML = `<p>${translations[currentLanguage].emptyCart}</p>`;
        cartFooter.style.display = 'none';
        return;
    }
    
    cartFooter.style.display = 'block';
    cartItems.innerHTML = cart.map(item => `
        <div class="cart-item">
            <div class="cart-item-details">
                <h4>${item.team} - ${item.kit}</h4>
                <p>${translations[currentLanguage].playerName}: ${item.name}</p>
                <p>${translations[currentLanguage].playerNumber}: ${item.number}</p>
                <p>x${item.quantity}</p>
            </div>
            <div>
                <div class="cart-item-price">${item.total}₪</div>
                <button class="remove-btn" onclick="removeFromCart(${item.id})">הסר</button>
            </div>
        </div>
    `).join('');
    
    const total = cart.reduce((sum, item) => sum + item.total, 0);
    document.getElementById('cartTotal').textContent = `${total}₪`;
}

function goToCart() {
    displayCartItems();
    showPage('cartPage');
}

function updateCartCount() {
    const count = cart.reduce((sum, item) => sum + item.quantity, 0);
    document.getElementById('cartCount').textContent = count;
}

function saveCart() {
    localStorage.setItem('sheKitCart', JSON.stringify(cart));
}

function loadCart() {
    const saved = localStorage.getItem('sheKitCart');
    if (saved) {
        cart = JSON.parse(saved);
        updateCartCount();
    }
}

function resetCustomizationForm() {
    document.getElementById('playerName').value = '';
    document.getElementById('playerNumber').value = '';
    document.getElementById('shortsPack').checked = false;
    document.querySelectorAll('.addon').forEach(cb => cb.checked = false);
    document.querySelector('input[name="version"][value="fan"]').checked = true;
    document.getElementById('quantity').value = 1;
    calculatePrice();
}

window.addEventListener('load', () => {
    applyLanguage(currentLanguage);
});
